/**
 * 되묻기가 닿지 않은 순간 (RULES 8.2)
 *
 * 사용자가 **직접** 질문을 못 알아듣겠다고 말하거나 되묻기 자체를 거절한 경우를
 * 센다. 상태를 추정하지 않는다 — 지쳤는지 방어하는지는 여기서 알 수 없고 알려고도
 * 하지 않는다. 보는 것은 사용자가 화면에 쓴 말 하나뿐이다.
 *
 * `stalled`(길이)로는 이 순간을 잡을 수 없다. 운영에서 관찰된 예:
 *
 *   AI  사수가 생겨야겠지 싶다는 지금 회사에서, 사수가 생기기 전까지 …
 *   U   무슨말인지 모르겠어            ← 9자. 앞선 중앙값 13자의 0.69배라 비율에 안 걸린다
 *   AI  사수가 생겨야겠지 싶다면, 사수가 생기면 회사에서 무엇을 …
 *
 * 못 알아듣겠다고 말한 사람에게 같은 틀의 질문이 한 번 더 갔다. 길이는 이 일을
 * 설명하지 못하므로 말 자체를 본다.
 *
 * **고민에 대한 모름과 질문에 대한 모름을 가른다.** `내가 성장할 수 있을지
 * 모르겠어`는 훌륭한 답이지 혼란이 아니다. 그래서 모름의 대상이 `말·소리·질문`처럼
 * 방금 받은 물음을 가리킬 때만 센다.
 */

export type ConfusionTurn = { role: "user" | "assistant"; text: string };

/** 질문이 닿지 않았다고 말하는 꼴. 대상이 고민이 아니라 방금의 물음이다. */
const NOT_UNDERSTOOD =
  /(무슨|뭔|무신)\s*(말|소리|얘기|이야기)|뭐라는\s*(거|건|게)|질문[이을]?\s*(이해|모르|어렵)|뭘\s*(물어|묻)|이해(가|를)?\s*(안|못)\s*(돼|되|가|하)|(말|질문)이\s*(너무\s*)?(어렵|어려|복잡)/u;

/** 되묻기 자체를 그만두라는 말. 고민을 그만두겠다는 뜻이 아니므로 종료와 다르다. */
const PROBE_REFUSED =
  /알아서\s*뭐(하게|해)|왜\s*(자꾸\s*)?(물어|묻)|그만\s*(물어|묻)|계속\s*물어|답답해/u;

/** 마지막 사용자 발화가 방금의 질문을 되받았는가.
 *
 * 마지막 하나만 본다. 이 신호는 바로 그 턴의 질문에 대한 반응이고, 지난 턴의 혼란은
 * 그때 이미 다뤘거나 다뤄지지 않은 채로 지나간 것이다.
 */
export function isConfused(turns: readonly ConfusionTurn[]): boolean {
  const last = [...turns].reverse().find((turn) => turn.role === "user");
  if (!last) return false;
  const text = last.text.normalize("NFC");
  return NOT_UNDERSTOOD.test(text) || PROBE_REFUSED.test(text);
}
